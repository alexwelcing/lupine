"""Execute only the isolated synthetic author test file and retain exact evidence."""
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import time

BASE = Path(__file__).resolve().parent
ROOT = BASE.parents[1]
label = sys.argv[1]
if label not in ('author-first', 'author-second', 'author-third'):
    raise SystemExit('unsupported receipt slot')
paths = [BASE / p for p in (
    'promotion/scripts/li_v3_growth_hint_shape.py',
    'promotion/tests/test_li_v3_growth_hint_shape.py',
    'promotion/docs/li-v3-growth-hint-shape-plan.md')]
run = BASE / 'receipts' / label
run.mkdir(parents=True)


def binding(path):
    raw = path.read_bytes()
    return {'path': str(path), 'bytes': len(raw),
            'sha256': hashlib.sha256(raw).hexdigest()}


before = [binding(p) for p in paths]
for path in paths:
    (run / path.name).write_bytes(path.read_bytes())
command = [sys.executable, '-B', str(paths[1]), '-v']
started, timer = datetime.now(timezone.utc).isoformat(), time.monotonic()
outcome = 'completed'
try:
    completed = subprocess.run(command, cwd=ROOT, stdout=subprocess.PIPE,
                               stderr=subprocess.PIPE, timeout=30)
    stdout, stderr, code = completed.stdout, completed.stderr, completed.returncode
except subprocess.TimeoutExpired as error:
    stdout, stderr, code = error.stdout or b'', error.stderr or b'', None
    outcome = 'timeout'
except OSError:
    stdout, stderr, code, outcome = b'', b'', None, 'launch_error'
(run / 'stdout.txt').write_bytes(stdout)
(run / 'stderr.txt').write_bytes(stderr)
receipt = {
    'schema': 'lupine.discovery.growth_hint_production_author_execution.v1',
    'command': command, 'cwd': str(ROOT), 'started_utc': started,
    'finished_utc': datetime.now(timezone.utc).isoformat(),
    'elapsed_seconds': time.monotonic() - timer, 'exit_code': code,
    'outcome': outcome, 'before': before, 'after': [binding(p) for p in paths],
    'stdout': binding(run / 'stdout.txt'), 'stderr': binding(run / 'stderr.txt'),
    'scope': ('Generated byte fixtures with unchanged G29 synthetic helpers imported; '
              'all production dependencies mocked before wrapper/guard checks; no actual '
              'receipt/archive/private body, network or scientific test.')}
(run / 'execution.json').write_text(json.dumps(receipt, indent=2, sort_keys=True) + '\n')
print(stderr.decode('utf-8', errors='replace'))
print(json.dumps({'receipt': str(run / 'execution.json'), 'exit_code': code,
                  'outcome': outcome, 'elapsed_seconds': receipt['elapsed_seconds']}))
raise SystemExit(0 if code == 0 else 1)
