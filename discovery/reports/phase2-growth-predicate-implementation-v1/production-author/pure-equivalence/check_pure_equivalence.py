"""Exact whole-report comparisons on a fixed generated-fixture matrix."""
from pathlib import Path
import ast
import hashlib
import importlib.util
import json
import os
import socket
import sys
from unittest.mock import patch
import zipfile

BASE = Path(__file__).resolve().parent
ROOT = BASE.parents[1]
sys.dont_write_bytecode = True
violations = []

def audit(event, args):
    if event == 'open' and isinstance(args[0], (str, bytes, os.PathLike)):
        if Path(os.fsdecode(args[0])).absolute().is_relative_to(ROOT / '.cache/li-v3-custody'):
            violations.append('REAL_PRIVATE_OPEN'); raise AssertionError('actual private source forbidden')
    if event.startswith('socket.') or event in ('subprocess.Popen', 'os.system', 'os.posix_spawn'):
        violations.append('EXTERNAL_EFFECT'); raise AssertionError('external effect forbidden')

sys.addaudithook(audit)

def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec); spec.loader.exec_module(module)
    return module

pure_path = ROOT / '.cache/phase2-growth-predicate-candidate-v1/growth_predicate_audit.py'
production_path = BASE / 'promotion/scripts/li_v3_growth_predicate_audit.py'
assert hashlib.sha256(pure_path.read_bytes()).hexdigest() == '167c8e3d0cba758057c60991debe8d831c8638da5ce3dbd1a183503c46efea11'
assert hashlib.sha256(production_path.read_bytes()).hexdigest() == '1bcbc0d16c2e9a516f3bce0ed98e5fd65d6ce4a26b7942f7dedd7724e201fc55'
P = load('held_pure_audit_equivalence', pure_path)
T = load('production_fixture_equivalence', BASE / 'promotion/tests/test_li_v3_growth_predicate_audit.py')
M = T.M
fixtures = [T.packed()[0], b'', b'x', b'x' * 21]
for field, value in [(0,b'FAIL'),(1,1),(2,1),(3,3),(6,0),(7,1)]:
    fixtures.append(T.packed(end_override={field:value})[0])
for field, value in [(3,1),(4,12),(2,21),(15,0xA000<<16),(15,0x10),(9,123),(16,1),(16,0xFFFFFFFF)]:
    fixtures.append(T.packed([{'c':{field:value}},{},{},{}])[0])
for field, value in [(0,b'FAIL'),(1,21),(2,8),(3,8),(4,1),(5,34),(6,13),(7,1),(8,1),(10,65535)]:
    fixtures.append(T.packed([{'l':{field:value}},{},{},{}])[0])
for name in ('../private','unknown.xml','/x','x%20','x\\y'):
    fixtures.append(T.packed([{'name':name},{},{},{}])[0])
for initial in (0,1,7,65535):
    fixtures.append(T.packed([{'extra':T.shape(initial)},{},{},{}])[0])
for extra in (b'x',b'12345678',T.shape(padding=b'x'),T.shape(padding=b'\x00'*512)):
    fixtures.append(T.packed([{'extra':extra},{},{},{}])[0])
fixtures += [T.packed([{}, {'c':{16:0}}, {'l':{6:43}}, {}])[0],
             T.packed([{'l':{10:len(T.shape())+5}},{'l':{10:5,6:19}},{},{}])[0],
             T.packed([{'c':{3:1}},{},{'l':{6:43}},{'extra':T.shape(padding=b'x')}])[0],
             T.packed([{}, {}, {}])[0], T.packed(tail=b'x')[0]]
raw = T.packed()[0]
fixtures += [raw[:-n] for n in range(1,23)]
comparisons = 0
with patch.object(zipfile.ZipFile,'open',side_effect=AssertionError('member open forbidden')), patch.object(M.custody,'_xml',side_effect=AssertionError('XML forbidden')):
    for raw in fixtures:
        for selected in (False,True):
            assert P.inspect_synthetic_headers(raw,selected_growth=selected) == M.inspect_synthetic_headers(raw,selected_growth=selected)
            comparisons += 1
print(json.dumps({'fixture_count':len(fixtures),'complete_report_comparisons':comparisons,'all_equal':True,
                  'guard_violations':violations,'source_sha256':hashlib.sha256(production_path.read_bytes()).hexdigest(),
                  'pure_sha256':hashlib.sha256(pure_path.read_bytes()).hexdigest(),
                  'scope':'Generated bytes only, exact pure API outputs; no production context or actual source operation'},sort_keys=True))
assert not violations
