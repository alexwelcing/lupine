const PipelineVisualizer = memo(function PipelineVisualizer({
  step,
}: {
  step: GenerationStep;
}) {
  const steps: { id: GenerationStep; label: string; icon: typeof FileText; desc: string }[] = [
    { id: 'parse', label: 'Parse', icon: FileText, desc: 'Parse input → identify compound' },
    { id: 'fetch', label: 'Fetch', icon: Database, desc: 'Query 3D coordinates' },
    { id: 'render', label: 'Render', icon: Box, desc: 'Build 3D scene' },
  ];

  const stepIndex =
    step === 'parse' ? 0 : step === 'fetch' ? 1 : step === 'render' ? 2 : step === 'done' ? 3 : -1;

  return (
    <div className="w-full py-16 px-6">
      <div className="max-w-3xl mx-auto">
        <div className="flex items-center justify-between relative">
          {/* Connecting lines */}
          <div className="absolute top-6 left-0 right-0 h-px bg-[rgba(255,255,255,0.08)]" />
          <motion.div
            className="absolute top-6 left-0 h-px bg-gradient-to-r from-lupi-violet to-[#00E5FF]"
            initial={{ width: '0%' }}
            animate={{
              width: step === 'done' ? '100%' : step === 'idle' || step === 'error' ? '0%' : `${(stepIndex / 2) * 100}%`,
            }}
            transition={{ duration: 0.8, ease: [0.16, 1, 0.3, 1] as [number, number, number, number] }}
          />

          {steps.map((s, i) => {
            const Icon = s.icon;
            const isActive = i <= stepIndex && step !== 'idle' && step !== 'error';
            const isCurrent = i === stepIndex && step !== 'done';

            return (
              <div key={s.id} className="relative flex flex-col items-center z-10">
                <motion.div
                  animate={{
                    scale: isCurrent ? 1.1 : 1,
                    borderColor: isActive ? '#7B5CFF' : 'rgba(255,255,255,0.15)',
                    backgroundColor: isActive ? 'rgba(123,92,255,0.15)' : '#0A0A12',
                  }}
                  className="w-12 h-12 rounded-full border-2 flex items-center justify-center"
                >
                  <Icon
                    className={`w-5 h-5 ${
                      isActive ? 'text-lupi-violet' : 'text-[rgba(255,255,255,0.3)]'
                    }`}
                  />
                </motion.div>

                {/* Pulse dot for current step */}
                {isCurrent && (
                  <motion.div
                    className="absolute top-0 right-0 w-3 h-3 bg-[#00E5FF] rounded-full"
                    animate={{ scale: [1, 1.3, 1], opacity: [1, 0.6, 1] }}
                    transition={{ duration: 1.5, repeat: Infinity }}
                  />
                )}

                <p
                  className={`mt-2 text-[13px] font-medium ${
                    isActive ? 'text-white' : 'text-[rgba(255,255,255,0.4)]'
                  }`}
                >
                  {s.label}
                </p>
                <p className="mt-0.5 text-[11px] text-[rgba(255,255,255,0.3)] max-w-[120px] text-center">
                  {s.desc}
                </p>
              </div>
            );
          })}
        </div>
      </div>
    </div>
  );
});

