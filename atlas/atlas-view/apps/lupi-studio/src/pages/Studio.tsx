const CPK_COLORS: Record<string, string> = {
  H: '#FFFFFF',
  C: '#909090',
  N: '#3050F8',
  O: '#FF0D0D',
  F: '#90E050',
  P: '#FF8000',
  S: '#FFFF30',
  Cl: '#1FF01F',
  Fe: '#E06633',
  Cu: '#C78033',
  Zn: '#7D80B0',
};

function getAtomColor(element: string): string {
  return CPK_COLORS[element] || '#CCCCCC';
}

// ============================
// Property Panel Component
// ============================
function PropertyPanel({
  atoms,
  moleculeName,
  source,
  timestamp,
}: {
  atoms: Atom[];
  moleculeName: string;
  source: string;
  timestamp: number;
}) {
  const formula = calculateFormula(atoms);
  const weight = calculateMolecularWeight(atoms);
  const atomCounts = getAtomCounts(atoms);
  const maxCount = Math.max(...Object.values(atomCounts));

  return (
    <div className="space-y-4">
      <h3 className="font-body text-[14px] font-medium text-white tracking-wide">
        Properties
      </h3>

      {/* Molecular Formula */}
      <div>
        <p className="text-[11px] text-[rgba(255,255,255,0.4)] uppercase tracking-wider mb-1.5">
          Formula
        </p>
        <div className="font-mono text-[18px] flex flex-wrap gap-0.5">
          {formula.split(/([A-Z][a-z]?)(\d*)/).filter(Boolean).map((part, i) => {
            const isElement = /^[A-Z][a-z]?$/.test(part);
            if (isElement) {
              return (
                <span
                  key={i}
                  style={{ color: getAtomColor(part) }}
                  className="font-medium"
                >
                  {part}
                </span>
              );
            }
            return (
              <sub key={i} className="text-[13px] text-[rgba(255,255,255,0.7)]">
                {part}
              </sub>
            );
          })}
        </div>
      </div>

      {/* Atom Breakdown */}
      <div>
        <p className="text-[11px] text-[rgba(255,255,255,0.4)] uppercase tracking-wider mb-2">
          Atom Breakdown
        </p>
        <div className="space-y-1.5">
          {Object.entries(atomCounts)
            .sort((a, b) => b[1] - a[1])
            .map(([element, count]) => (
              <div key={element} className="flex items-center gap-2">
                <span
                  className="w-2.5 h-2.5 rounded-full shrink-0"
                  style={{ backgroundColor: getAtomColor(element) }}
                />
                <span className="text-[12px] text-[rgba(255,255,255,0.6)] w-6">
                  {element}
                </span>
                <div className="flex-1 h-1.5 bg-[rgba(255,255,255,0.08)] rounded-full overflow-hidden">
                  <motion.div
                    initial={{ width: 0 }}
                    animate={{ width: `${(count / maxCount) * 100}%` }}
                    transition={{ duration: 0.5, ease: [0.16, 1, 0.3, 1] as [number, number, number, number] }}
                    className="h-full rounded-full"
                    style={{ backgroundColor: getAtomColor(element) }}
                  />
                </div>
                <span className="text-[12px] text-white font-mono w-5 text-right">
                  {count}
                </span>
              </div>
            ))}
        </div>
      </div>

      {/* Molecular Weight */}
      <div className="flex justify-between items-center">
        <span className="text-[11px] text-[rgba(255,255,255,0.4)] uppercase tracking-wider">
          Weight
        </span>
        <span className="text-[14px] text-white font-mono">
          {weight.toFixed(2)} <span className="text-[12px] text-[rgba(255,255,255,0.4)]">g/mol</span>
        </span>
      </div>

      {/* Atom Count */}
      <div className="flex justify-between items-center">
        <span className="text-[11px] text-[rgba(255,255,255,0.4)] uppercase tracking-wider">
          Atoms
        </span>
        <span className="text-[14px] text-white font-mono">
          {atoms.length} <span className="text-[12px] text-[rgba(255,255,255,0.4)]">total</span>
        </span>
      </div>

      {/* Source */}
      <div className="flex justify-between items-center">
        <span className="text-[11px] text-[rgba(255,255,255,0.4)] uppercase tracking-wider">
          Source
        </span>
        <span
          className={`text-[12px] font-mono ${
            source === 'PubChem'
              ? 'text-[#00E5FF]'
              : source === 'AI'
              ? 'text-lupi-violet'
              : 'text-[rgba(255,255,255,0.6)]'
          }`}
        >
          {source}
        </span>
      </div>

      {/* Molecule Name */}
      <div className="flex justify-between items-center">
        <span className="text-[11px] text-[rgba(255,255,255,0.4)] uppercase tracking-wider">
          Name
        </span>
        <span className="text-[12px] text-white">{moleculeName}</span>
      </div>

      {/* Timestamp */}
      <div className="flex justify-between items-center">
        <span className="text-[11px] text-[rgba(255,255,255,0.4)] uppercase tracking-wider">
          Generated
        </span>
        <span className="text-[12px] text-[rgba(255,255,255,0.3)]">
          {formatTimestamp(timestamp)}
        </span>
      </div>
    </div>
  );
}

